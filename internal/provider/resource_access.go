// Service accounts

var _ resource.ResourceWithImportState = (*serviceAccountResource)(nil)

func newServiceAccountResource() resource.Resource { return &serviceAccountResource{} }

type serviceAccountResource struct{ base }

type serviceAccountModel struct {
	ID                types.String `tfsdk:"id"`
	ProjectID         types.String `tfsdk:"project_id"`
	Name              types.String `tfsdk:"name"`
	Group             types.String `tfsdk:"group"`
	Status            types.String `tfsdk:"status"`
	CreationTimestamp types.String `tfsdk:"creation_timestamp"`
}

func (r *serviceAccountResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_service_account"
}

func (r *serviceAccountResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A project service account. Give it API tokens with `kkp_service_account_token`.",
		Attributes: map[string]schema.Attribute{
			"id":         idAttribute("Service account ID, generated by KKP."),
			"project_id": projectIDAttribute(),
			"name":       schema.StringAttribute{Required: true, MarkdownDescription: "Display name, unique within the project."},
			"group": schema.StringAttribute{
				Required:            true,
				MarkdownDescription: "Role in the project: `editors`, `viewers` or `projectmanagers`.",
				Validators:          []validator.String{stringvalidator.OneOf("editors", "viewers", "projectmanagers")},
			},
			"status":             schema.StringAttribute{Computed: true},
			"creation_timestamp": idAttribute(""),
		},
	}
}

func (r *serviceAccountResource) fill(m *serviceAccountModel, projectID string, sa *client.ServiceAccount) {
	m.ID = types.StringValue(sa.ID)
	m.ProjectID = types.StringValue(projectID)
	m.Name = types.StringValue(sa.Name)
	m.Group = types.StringValue(groupRole(sa.Group, projectID))
	m.Status = types.StringValue(sa.Status)
	m.CreationTimestamp = types.StringValue(sa.CreationTimestamp)
}

func (r *serviceAccountResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan serviceAccountModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	project := r.project(plan.ProjectID, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}
	sa, err := r.client().CreateServiceAccount(ctx, project, plan.Name.ValueString(), plan.Group.ValueString())
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot create service account", err)
		return
	}
	r.fill(&plan, project, sa)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *serviceAccountResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state serviceAccountModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	sa, err := r.client().GetServiceAccount(ctx, state.ProjectID.ValueString(), state.ID.ValueString())
	if client.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot read service account", err)
		return
	}
	r.fill(&state, state.ProjectID.ValueString(), sa)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *serviceAccountResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan serviceAccountModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	project := plan.ProjectID.ValueString()
	sa, err := r.client().UpdateServiceAccount(ctx, project, client.ServiceAccount{
		ObjectMeta: client.ObjectMeta{ID: plan.ID.ValueString(), Name: plan.Name.ValueString()},
		Group:      plan.Group.ValueString(),
	})
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot update service account", err)
		return
	}
	r.fill(&plan, project, sa)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *serviceAccountResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state serviceAccountModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client().DeleteServiceAccount(ctx, state.ProjectID.ValueString(), state.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		addAPIError(&resp.Diagnostics, "Cannot delete service account", err)
	}
}

func (r *serviceAccountResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	parts, err := splitID(req.ID, 2, "<project_id>/<service_account_id>")
	if err != nil {
		resp.Diagnostics.AddError("Invalid import ID", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("project_id"), parts[0])...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), parts[1])...)
}

// Service account tokens

func newServiceAccountTokenResource() resource.Resource { return &serviceAccountTokenResource{} }

type serviceAccountTokenResource struct{ base }

type serviceAccountTokenModel struct {
	ID                types.String `tfsdk:"id"`
	ProjectID         types.String `tfsdk:"project_id"`
	ServiceAccountID  types.String `tfsdk:"service_account_id"`
	Name              types.String `tfsdk:"name"`
	Token             types.String `tfsdk:"token"`
	Expiry            types.String `tfsdk:"expiry"`
	CreationTimestamp types.String `tfsdk:"creation_timestamp"`
}

func (r *serviceAccountTokenResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_service_account_token"
}

func (r *serviceAccountTokenResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "An API token of a project service account. KKP shows the secret only once, when the token is created, " +
			"so the provider keeps it in state: treat the state as a secret. Tokens cannot be imported.",
		Attributes: map[string]schema.Attribute{
			"id":                 idAttribute("Token ID, generated by KKP."),
			"project_id":         projectIDAttribute(),
			"service_account_id": replaceString(true, "Service account the token belongs to."),
			"name":               schema.StringAttribute{Required: true, MarkdownDescription: "Display name. Renaming keeps the token."},
			"token": schema.StringAttribute{
				Computed:            true,
				Sensitive:           true,
				MarkdownDescription: "The bearer token. Use it as this provider's `token`, or for scripts against the KKP API.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"expiry":             idAttribute("When the token expires (KKP issues tokens valid for three years)."),
			"creation_timestamp": idAttribute(""),
		},
	}
}

func (r *serviceAccountTokenResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan serviceAccountTokenModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	project := r.project(plan.ProjectID, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}
	t, err := r.client().CreateServiceAccountToken(ctx, project, plan.ServiceAccountID.ValueString(), plan.Name.ValueString())
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot create service account token", err)
		return
	}
	plan.ID = types.StringValue(t.ID)
	plan.ProjectID = types.StringValue(project)
	plan.Token = types.StringValue(t.Token)
	plan.Expiry = types.StringValue(t.Expiry)
	plan.CreationTimestamp = types.StringValue(t.CreationTimestamp)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *serviceAccountTokenResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state serviceAccountTokenModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	t, err := r.client().GetServiceAccountToken(ctx, state.ProjectID.ValueString(), state.ServiceAccountID.ValueString(), state.ID.ValueString())
	if client.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot read service account token", err)
		return
	}
	if t.Invalidated {
		resp.State.RemoveResource(ctx)
		return
	}
	state.Name = types.StringValue(t.Name)
	state.Expiry = types.StringValue(t.Expiry)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *serviceAccountTokenResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan serviceAccountTokenModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	t, err := r.client().RenameServiceAccountToken(ctx, plan.ProjectID.ValueString(), plan.ServiceAccountID.ValueString(), plan.ID.ValueString(), plan.Name.ValueString())
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot rename service account token", err)
		return
	}
	plan.Name = types.StringValue(t.Name)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *serviceAccountTokenResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state serviceAccountTokenModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	err := r.client().DeleteServiceAccountToken(ctx, state.ProjectID.ValueString(), state.ServiceAccountID.ValueString(), state.ID.ValueString())
	if err != nil && !client.IsNotFound(err) {
		addAPIError(&resp.Diagnostics, "Cannot delete service account token", err)
	}
}

// Project members

var _ resource.ResourceWithImportState = (*projectMemberResource)(nil)

func newProjectMemberResource() resource.Resource { return &projectMemberResource{} }

type projectMemberResource struct{ base }

type projectMemberModel struct {
	ID        types.String `tfsdk:"id"`
	ProjectID types.String `tfsdk:"project_id"`
	Email     types.String `tfsdk:"email"`
	Group     types.String `tfsdk:"group"`
}

func (r *projectMemberResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_project_member"
}

func (r *projectMemberResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "Gives a user (by e-mail) a role in a project. Managing owners needs an owner token.",
		Attributes: map[string]schema.Attribute{
			"id":         idAttribute("KKP user ID."),
			"project_id": projectIDAttribute(),
			"email":      replaceString(true, "The user's e-mail address, as their identity provider reports it."),
			"group": schema.StringAttribute{
				Required:            true,
				MarkdownDescription: "Role: `owners`, `editors`, `viewers` or `projectmanagers`.",
				Validators:          []validator.String{stringvalidator.OneOf("owners", "editors", "viewers", "projectmanagers")},
			},
		},
	}
}

func (r *projectMemberResource) find(ctx context.Context, projectID, id string) (*client.User, error) {
	users, err := r.client().ListProjectMembers(ctx, projectID)
	if err != nil {
		return nil, err
	}
	for i := range users {
		if users[i].ID == id {
			return &users[i], nil
		}
	}
	return nil, nil
}

func (r *projectMemberResource) fill(m *projectMemberModel, projectID string, u *client.User) {
	m.ID = types.StringValue(u.ID)
	m.ProjectID = types.StringValue(projectID)
	m.Email = types.StringValue(u.Email)
	for _, p := range u.Projects {
		if p.ID == projectID {
			m.Group = types.StringValue(groupRole(p.GroupPrefix, projectID))
		}
	}
}

func (r *projectMemberResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan projectMemberModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	project := r.project(plan.ProjectID, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}
	u, err := r.client().AddProjectMember(ctx, project, plan.Email.ValueString(), plan.Group.ValueString())
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot add project member", err)
		return
	}
	r.fill(&plan, project, u)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *projectMemberResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state projectMemberModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	u, err := r.find(ctx, state.ProjectID.ValueString(), state.ID.ValueString())
	if client.IsNotFound(err) || (err == nil && u == nil) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot read project members", err)
		return
	}
	r.fill(&state, state.ProjectID.ValueString(), u)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *projectMemberResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan projectMemberModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	project := plan.ProjectID.ValueString()
	cur, err := r.find(ctx, project, plan.ID.ValueString())
	if err == nil && cur == nil {
		resp.Diagnostics.AddError("Project member is gone", "The member was removed outside of Terraform; run apply again to re-add it.")
		return
	}
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot read project members", err)
		return
	}
	u, err := r.client().UpdateProjectMember(ctx, project, *cur, plan.Group.ValueString())
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot update project member", err)
		return
	}
	r.fill(&plan, project, u)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *projectMemberResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state projectMemberModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client().RemoveProjectMember(ctx, state.ProjectID.ValueString(), state.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		addAPIError(&resp.Diagnostics, "Cannot remove project member", err)
	}
}

func (r *projectMemberResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	parts, err := splitID(req.ID, 2, "<project_id>/<user_id>")
	if err != nil {
		resp.Diagnostics.AddError("Invalid import ID", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("project_id"), parts[0])...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), parts[1])...)
}
