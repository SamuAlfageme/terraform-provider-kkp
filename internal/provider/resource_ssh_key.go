package provider

import (
	"context"
	"strings"

	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/types"

	"github.com/SamuAlfageme/terraform-provider-kkp/internal/client"
)

var _ resource.ResourceWithImportState = (*sshKeyResource)(nil)

func newSSHKeyResource() resource.Resource { return &sshKeyResource{} }

type sshKeyResource struct{ base }

type sshKeyModel struct {
	ID                types.String `tfsdk:"id"`
	ProjectID         types.String `tfsdk:"project_id"`
	Name              types.String `tfsdk:"name"`
	PublicKey         types.String `tfsdk:"public_key"`
	Fingerprint       types.String `tfsdk:"fingerprint"`
	CreationTimestamp types.String `tfsdk:"creation_timestamp"`
}

func projectIDAttribute() schema.StringAttribute {
	return schema.StringAttribute{
		Optional:            true,
		Computed:            true,
		MarkdownDescription: "Project ID. Defaults to the provider's `project_id`.",
		PlanModifiers:       []planmodifier.String{stringplanmodifier.RequiresReplace(), stringplanmodifier.UseStateForUnknown()},
	}
}

func idAttribute(desc string) schema.StringAttribute {
	return schema.StringAttribute{
		Computed:            true,
		MarkdownDescription: desc,
		PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
	}
}

func replaceString(required bool, desc string) schema.StringAttribute {
	return schema.StringAttribute{
		Required:            required,
		Optional:            !required,
		MarkdownDescription: desc,
		PlanModifiers:       []planmodifier.String{stringplanmodifier.RequiresReplace()},
	}
}

func (r *sshKeyResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_ssh_key"
}

func (r *sshKeyResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "An SSH public key stored in a project. Assign it to clusters with `kkp_cluster.ssh_key_ids`; " +
			"KKP's user SSH key agent then puts it on every node.",
		Attributes: map[string]schema.Attribute{
			"id":                 idAttribute("Key ID, generated by KKP."),
			"project_id":         projectIDAttribute(),
			"name":               replaceString(true, "Display name, unique within the project."),
			"public_key":         replaceString(true, "Public key in OpenSSH authorized_keys format."),
			"fingerprint":        idAttribute("MD5 fingerprint, as KKP shows it."),
			"creation_timestamp": idAttribute(""),
		},
	}
}

func (r *sshKeyResource) fill(m *sshKeyModel, projectID string, k *client.SSHKey) {
	m.ID = types.StringValue(k.ID)
	m.ProjectID = types.StringValue(projectID)
	m.Name = types.StringValue(k.Name)
	// KKP trims the key; keep the configured spelling when it only differs in surrounding whitespace.
	if strings.TrimSpace(m.PublicKey.ValueString()) != strings.TrimSpace(k.Spec.PublicKey) {
		m.PublicKey = types.StringValue(k.Spec.PublicKey)
	}
	m.Fingerprint = types.StringValue(k.Spec.Fingerprint)
	m.CreationTimestamp = types.StringValue(k.CreationTimestamp)
}

func (r *sshKeyResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan sshKeyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	project := r.project(plan.ProjectID, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}
	k, err := r.client().CreateSSHKey(ctx, project, plan.Name.ValueString(), strings.TrimSpace(plan.PublicKey.ValueString()))
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot create SSH key", err)
		return
	}
	r.fill(&plan, project, k)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *sshKeyResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state sshKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	k, err := r.client().GetSSHKey(ctx, state.ProjectID.ValueString(), state.ID.ValueString())
	if client.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot read SSH key", err)
		return
	}
	r.fill(&state, state.ProjectID.ValueString(), k)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *sshKeyResource) Update(context.Context, resource.UpdateRequest, *resource.UpdateResponse) {
	// Every attribute forces replacement.
}

func (r *sshKeyResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state sshKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client().DeleteSSHKey(ctx, state.ProjectID.ValueString(), state.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		addAPIError(&resp.Diagnostics, "Cannot delete SSH key", err)
	}
}

func (r *sshKeyResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	parts, err := splitID(req.ID, 2, "<project_id>/<key_id>")
	if err != nil {
		resp.Diagnostics.AddError("Invalid import ID", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("project_id"), parts[0])...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), parts[1])...)
}
