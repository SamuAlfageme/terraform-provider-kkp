package provider

import (
	"context"
	"time"

	"github.com/hashicorp/terraform-plugin-framework-timeouts/resource/timeouts"
	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/types"

	"github.com/SamuAlfageme/terraform-provider-kkp/internal/client"
)

var (
	_ resource.ResourceWithImportState = (*projectResource)(nil)
	_ resource.ResourceWithConfigure   = (*projectResource)(nil)
)

func newProjectResource() resource.Resource { return &projectResource{} }

type projectResource struct{ base }

type projectModel struct {
	ID                types.String   `tfsdk:"id"`
	Name              types.String   `tfsdk:"name"`
	Labels            types.Map      `tfsdk:"labels"`
	Status            types.String   `tfsdk:"status"`
	CreationTimestamp types.String   `tfsdk:"creation_timestamp"`
	Timeouts          timeouts.Value `tfsdk:"timeouts"`
}

func (r *projectResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_project"
}

func (r *projectResource) Schema(ctx context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A KKP project. Creating and deleting projects needs a user token: KKP does not let " +
			"service account tokens create projects, and only owners can delete them.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Project ID, generated by KKP.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"name":   schema.StringAttribute{Required: true, MarkdownDescription: "Display name."},
			"labels": schema.MapAttribute{Optional: true, ElementType: types.StringType, MarkdownDescription: "Labels; KKP passes them on to the project's clusters as inherited labels."},
			"status": schema.StringAttribute{Computed: true, MarkdownDescription: "`Active`, `Inactive` or `Terminating`."},
			"creation_timestamp": schema.StringAttribute{
				Computed:      true,
				PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"timeouts": timeouts.Attributes(ctx, timeouts.Opts{Create: true, Delete: true}),
		},
	}
}

func (r *projectResource) fill(m *projectModel, p *client.Project) {
	m.ID = types.StringValue(p.ID)
	m.Name = types.StringValue(p.Name)
	m.Labels = mapKeep(p.Labels, m.Labels)
	m.Status = types.StringValue(p.Status)
	m.CreationTimestamp = types.StringValue(p.CreationTimestamp)
}

func (r *projectResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan projectModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	timeout, d := plan.Timeouts.Create(ctx, 5*time.Minute)
	resp.Diagnostics.Append(d...)
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()

	p, err := r.client().CreateProject(ctx, client.CreateProjectBody{Name: plan.Name.ValueString(), Labels: goMap(ctx, plan.Labels, &resp.Diagnostics)})
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot create project", err)
		return
	}
	// Save the ID right away so a failed wait does not leak the project.
	plan.ID = types.StringValue(p.ID)
	r.fill(&plan, p)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)

	err = waitFor(ctx, "project to become active", func() (bool, error) {
		var err error
		p, err = r.client().GetProject(ctx, plan.ID.ValueString())
		return err == nil && p.Status == client.ProjectActive, err
	})
	if err != nil {
		addAPIError(&resp.Diagnostics, "Project did not become active", err)
		return
	}
	r.fill(&plan, p)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *projectResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state projectModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	p, err := r.client().GetProject(ctx, state.ID.ValueString())
	if client.IsNotFound(err) || (err == nil && p.Status == client.ProjectTerminating) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot read project", err)
		return
	}
	r.fill(&state, p)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *projectResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan projectModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	cur, err := r.client().GetProject(ctx, plan.ID.ValueString())
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot read project", err)
		return
	}
	cur.Name = plan.Name.ValueString()
	cur.Labels = goMap(ctx, plan.Labels, &resp.Diagnostics)
	p, err := r.client().UpdateProject(ctx, *cur)
	if err != nil {
		addAPIError(&resp.Diagnostics, "Cannot update project", err)
		return
	}
	r.fill(&plan, p)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *projectResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state projectModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	timeout, d := state.Timeouts.Delete(ctx, 20*time.Minute)
	resp.Diagnostics.Append(d...)
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()

	id := state.ID.ValueString()
	if err := r.client().DeleteProject(ctx, id); err != nil && !client.IsNotFound(err) {
		addAPIError(&resp.Diagnostics, "Cannot delete project", err)
		return
	}
	// KKP deletes the project's clusters first, which can take a while.
	if err := waitGone(ctx, "project", func() error { _, err := r.client().GetProject(ctx, id); return err }); err != nil {
		addAPIError(&resp.Diagnostics, "Project was not deleted", err)
	}
}

func (r *projectResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
